// Regenerates app/lib/route-slugs.generated.ts.
//
// proxy.ts has to 404 unknown /destinations/<slug> and /visa/<slug> before the response is
// written, but importing the two data modules there pulls ~1.1 MB of page copy into the
// middleware bundle. This emits just the slugs, so the middleware imports a few hundred bytes.
//
// Run `npm run gen:slugs` after adding or renaming a destination or visa. The unit test
// tests/unit/route-slugs.test.mjs fails if this output and the data drift apart.
import { writeFileSync } from "node:fs";
import { destinations } from "../app/destinations/data.ts";
import { visas } from "../app/visa/data.ts";

const out = `// GENERATED by scripts/gen-route-slugs.mjs — do not edit by hand.
export const DESTINATION_SLUGS: readonly string[] = ${JSON.stringify(destinations.map((d) => d.slug).sort())};
export const VISA_SLUGS: readonly string[] = ${JSON.stringify(visas.map((v) => v.slug).sort())};
`;

writeFileSync(new URL("../app/lib/route-slugs.generated.ts", import.meta.url), out);
console.log(`wrote ${destinations.length} destination slugs, ${visas.length} visa slugs`);
